const dutiesFor = employee => {
  if (employee.id === 'admin' || employee.name === 'المدير العام') return templates.generalManager;
  if (employee.jobTitle === 'المدير التنفيذي') return templates.executiveManager;
  if (/مدير\s*اداري|مدير\s*إداري/.test(employee.jobTitle || '')) return templates.administrativeManager;
  if (employee.jobTitle === 'مدير قسم الخياطة') return templates.sewingManager;
  if (employee.jobTitle === 'مدير المبيعات') return templates.salesManager;
  if (employee.id === 'EMP-0017') return templates.salesTechnicalSupport;
  if (employee.id === 'EMP-0006' || (employee.jobTitle === 'فني دعم لوجستي' && ['مشرف', 'إدارة', 'admin'].includes(employee.level))) return templates.logisticsSupervisor;
  if (employee.jobTitle === 'فني دعم لوجستي') return templates.logisticsTechnician;
  if (employee.jobTitle === 'فني قص وخياطة') return templates.cuttingSewingTechnician;
  if (employee.jobTitle === 'فني تغليف وتشطيب') return templates.packagingTechnician;
  return templates.sewingTechnician;
};

